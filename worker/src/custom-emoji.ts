// Замена обычных эмодзи в текстах сообщений на кастомные из эмодзи-паков
// (разметка tg-emoji, Bot API). Иконки видны, пока у владельца бота активен
// Telegram Premium (или у бота есть Fragment-юзернейм); иначе клиенты
// показывают обычный эмодзи-фолбэк.

const MAP: [string, string][] = [
  // Набор для текстов (прислан владельцем через /emojiid)
  ["🧾", "5956561916573782596"],
  ["❌", "5778527486270770928"],
  ["✅", "5825794181183836432"],
  ["⏳", "5900104897885376843"],
  ["💳", "5927169041595634481"],
  ["🔒", "5879895758202735862"],
  ["💰", "5974217466270716579"],
  ["⚠️", "6028226658543082010"],
  ["⭐️", "5956561749070057536"],
  ["🤝", "5825794181183836432"],
  ["💬", "5994297722574737553"],
  ["👍", "5992199545151295755"],
  ["👎", "5994368422031397063"],
  // Набор из кнопок — те же иконки в текстах
  ["👤", "5886412370347036129"],
  ["🔍", "5874960879434338403"],
  ["🛡", "5886306834410640699"],
  ["🗂", "5967389567781703494"],
  ["ℹ️", "5897846616966041652"],
  ["↩️", "5875082500023258804"],
  ["🛒", "5920344347152224466"],
  ["💼", "5983399041197675256"],
];

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

const RULES = MAP.map(([emoji, id]) => {
  const base = emoji.replace(/️/g, "");
  return {
    re: new RegExp(`${escapeRe(base)}️?`, "g"),
    tag: `<tg-emoji emoji-id="${id}">${emoji}</tg-emoji>`,
  };
});

/** Подменяет известные эмодзи в HTML-тексте на кастомные из паков. */
export function emojify(html: string): string {
  let out = html;
  for (const { re, tag } of RULES) out = out.replace(re, tag);
  return out;
}
